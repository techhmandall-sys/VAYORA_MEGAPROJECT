"""Experiment X7: the assumptions moved together, by a Latin hypercube.

    python -m experiments.analysis.joint design   writes the points into the sweeps x7.yaml names
    python -m experiments.analysis.joint          judges the runs once the sweeps have run

EXPERIMENT_PROTOCOL.md sections 26 and 32. The hypercube's seed, ranges and size are in
experiments/configs/x7.yaml, fixed before any point was drawn. Each point sets the response to a request,
demand, supply and every passenger type's Weibull scale at once (a named cell of a sweep). B3 is its
baseline, and B4 and ORACLE are compared with it. Writes experiments/reports/x7-joint.json and .md.
"""

from __future__ import annotations

import json
import os
import statistics
import sys
import uuid
from pathlib import Path
from typing import Any

import yaml
from scipy import stats
from scipy.stats import qmc
from sqlalchemy import create_engine, make_url

from experiments.analysis.compare import REPORTS, differences, equivalence, load_analysis
from experiments.analysis.proximity import summary
from experiments.analysis.queries import run_query
from experiments.sweep import cell_label, named_cells
from sim.config import load_world

CONFIGS = Path(__file__).resolve().parents[1] / "configs"
CONFIG = CONFIGS / "x7.yaml"
SCALE = "weibull_scale_multiplier"


def load_x7(path: Path = CONFIG) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def draw(config: dict[str, Any], *, rounded: bool = True) -> list[dict[str, float]]:
    """The hypercube's points, each value rounded to the configured places (or not, to check the design)."""
    ranges = config["ranges"]
    unit = qmc.LatinHypercube(d=len(ranges), rng=config["seed"]).random(n=config["points"])
    places = config["decimals"] if rounded else None
    return [{name: round(float(low + u * (high - low)), places) if places is not None else float(low + u * (high - low))
             for (name, (low, high)), u in zip(ranges.items(), row, strict=True)} for row in unit]


def settings(point: dict[str, float], decimals: int) -> dict[str, float]:
    """A point as a sweep cell: dotted paths, the scale multiplier spread over every type."""
    base = load_world(CONFIGS / "world.yaml").demand.types
    out = {path: value for path, value in point.items() if path != SCALE}
    for name, kind in base.items():
        out[f"demand.types.{name}.weibull_scale_hours"] = round(kind.weibull_scale_hours * point[SCALE], decimals)
    return out


def write_design(config: dict[str, Any]) -> list[Path]:
    points = draw(config)
    parts = config["parts"]
    size = -(-len(points) // len(parts))
    written = []
    for k, part in enumerate(parts):
        cells = [{"name": f"p{n + 1:02d}", "set": settings(points[n], config["decimals"])}
                 for n in range(k * size, min((k + 1) * size, len(points)))]
        sweep = {"name": f"joint-lhs-{k + 1}", "baseline": config["baseline"], "variants": config["variants"],
                 "baseline_per_cell": True, "cells": cells}
        header = (f"# Experiment X7, part {k + 1} of {len(parts)} (EXPERIMENT_PROTOCOL.md sections 26 and 32).\n"
                  "# Generated by `python -m experiments.analysis.joint design` from configs/x7.yaml; do not edit\n"
                  "# by hand. Not offered in the what-if explorer.\n")
        path = CONFIGS / part["config"]
        path.write_text(header + yaml.safe_dump(sweep, sort_keys=False), encoding="utf-8")
        written.append(path)
    return written


def per_100(conn, run: str, variant: str) -> dict[int, float]:
    rows = run_query(conn, "primary_metric", run_id=uuid.UUID(run), variant=variant)
    return {r["seed"]: float(r["per_100"]) for r in rows if r["per_100"] is not None}


def judge(points: list[dict[str, Any]], config: dict[str, Any]) -> dict[str, Any]:
    low = [p for p in points if p["oracle"]["mean_difference"] < config["oracle_threshold"]]
    out_of_margin = [p["point"] for p in low if not p["b4_equivalence"]["equivalent"]]
    over_cap = [p["point"] for p in points if not p["oracle"]["mean_difference"] < config["oracle_cap"]]
    return {
        "H7.1": {"rule": f"where ORACLE - B3 is below {config['oracle_threshold']}, B4 - B3 is equivalent to zero",
                 "points_judged": [p["point"] for p in low], "not_equivalent": out_of_margin,
                 "holds": not out_of_margin},
        "H7.2": {"rule": f"ORACLE - B3 is below {config['oracle_cap']} at every point", "over_cap": over_cap,
                 "holds": not over_cap},
    }


def to_markdown(report: dict[str, Any]) -> str:
    lines = ["# Experiment X7: the assumptions moved together", "",
             f"Synthetic data (simulator), world h3, model h3, 30 paired seeds per point, B3 as each point's "
             f"baseline. A Latin hypercube of {len(report['points'])} points, seed {report['config']['seed']} "
             "(`experiments/configs/x7.yaml`). Hypotheses: docs/EXPERIMENT_PROTOCOL.md section 26, fixed before "
             "these runs.", "", "| Hypothesis | Rule | Holds |", "|---|---|---|"]
    lines += [f"| {k} | {v['rule']} | {'yes' if v['holds'] else 'NO'} |" for k, v in report["hypotheses"].items()]
    e = report["exploratory"]
    lines += ["", f"Exploratory: Spearman between ORACLE − B3 and B4 − B3 across points {e['spearman']:.3f}; "
                  f"largest |B4 − B3| {e['largest_b4']:.3f}.", "",
              "| Point | ρ | η | Searches/day | Rides/day | Scale × | B3 | ORACLE − B3 (95% CI) | B4 − B3 (95% CI) "
              "| B4 equivalence p |", "|---|---|---|---|---|---|---|---|---|---|"]
    for p in report["points"]:
        v, o, b = p["values"], p["oracle"], p["b4"]
        lines.append(
            f"| {p['point']} | {v['demand.intervention_response.early_release_probability']:.3f} "
            f"| {v['demand.intervention_response.annoyed_cancel_probability']:.3f} | {v['demand.searches_per_day']:.1f} "
            f"| {v['supply.rides_per_day']:.1f} | {v[SCALE]:.2f} | {p['b3_mean']:.2f} "
            f"| {o['mean_difference']:+.3f} ({o['ci_low']:+.3f} to {o['ci_high']:+.3f}) "
            f"| {b['mean_difference']:+.3f} ({b['ci_low']:+.3f} to {b['ci_high']:+.3f}) "
            f"| {p['b4_equivalence']['tost_p']:.4f} |")
    return "\n".join(lines)


def main() -> None:
    config = load_x7()
    if sys.argv[1:] == ["design"]:
        for path in write_design(config):
            print(f"wrote {path.relative_to(CONFIGS.parents[1])}")
        return
    analysis = load_analysis()
    url = os.environ.get("VAYORA_DB_URL")
    if not url:
        raise SystemExit("VAYORA_DB_URL is not set")
    drawn = draw(config)
    engine = create_engine(make_url(url).set(drivername="postgresql+psycopg"))
    points = []
    with engine.connect() as conn:
        for part in config["parts"]:
            sweep = yaml.safe_load((CONFIGS / part["config"]).read_text(encoding="utf-8"))
            for name, cell in named_cells(sweep):
                b3, b4, oracle = (per_100(conn, part["run"], cell_label(v, cell, name)) for v in ("B3", "B4", "ORACLE"))
                b4_diffs = differences(b3, b4)
                points.append({"point": name, "values": drawn[int(name[1:]) - 1], "settings": cell,
                               "b3_mean": statistics.fmean(b3.values()),
                               "b4": summary(b4_diffs, analysis), "oracle": summary(differences(b3, oracle), analysis),
                               "b4_equivalence": equivalence(b4_diffs, analysis["equivalence_margin"],
                                                             analysis["equivalence_alpha"])})
    report = {"config": config, "analysis": analysis, "hypotheses": judge(points, config),
              "exploratory": {
                  "spearman": float(stats.spearmanr([p["oracle"]["mean_difference"] for p in points],
                                                    [p["b4"]["mean_difference"] for p in points]).statistic),
                  "largest_b4": max(abs(p["b4"]["mean_difference"]) for p in points)},
              "points": points}
    stem = REPORTS / "x7-joint"
    stem.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    stem.with_suffix(".md").write_text(to_markdown(report) + "\n", encoding="utf-8")
    print(to_markdown(report))


if __name__ == "__main__":
    main()
